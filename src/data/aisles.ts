const KEYWORD_MAP = new Map<string, Aisle>();
for (const [aisle, words] of AISLE_KEYWORDS) {
  for (const w of words) {
    KEYWORD_MAP.set(w.toLowerCase(), aisle);
  }
}

export function classifyAisle(ingredientName: string): Aisle {
  const lower = ingredientName.toLowerCase().trim();
  if (!lower) return 'other';

  const exact = KEYWORD_MAP.get(lower);
  if (exact) return exact;

  // Word-boundary check, preferring longer phrases first
  for (const [aisle, words] of AISLE_KEYWORDS) {
    for (const kw of words) {
      const escaped = kw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const regex = new RegExp(`\\b${escaped}\\b`, 'i');
      if (regex.test(lower)) {
        return aisle;
      }
    }
  }

  return 'other';
}
